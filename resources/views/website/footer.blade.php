    window.tabChange = function(currentInput, event) {
        let currentField = $('#otp' + currentInput);
        let nextField = $('#otp' + (currentInput + 1));
        let prevField = $('#otp' + (currentInput - 1));

        // If Backspace is pressed, move to the previous input
        if (event.key === 'Backspace' || event.keyCode === 8) {
            if (prevField.length) {
                prevField.focus();
                prevField.val('');  // Optionally clear the previous input when moving back
            }
        } 
        // If a digit is entered, move to the next input
        else if (currentField.val().length === 1) {
            if (nextField.length) {
                nextField.focus();
            }
        }
    };

    // Function to validate that only digits are entered
    window.digitValidate = function(input) {
        input.value = input.value.replace(/[^0-9]/g, ''); // Allow only numbers
    };
});
